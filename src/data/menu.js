// ---- date helpers ----

export function addDays(date, days) {
  const d = new Date(date)
  d.setDate(d.getDate() + days)
  return d
}

export function toISODate(date) {
  const y = date.getFullYear()
  const m = String(date.getMonth() + 1).padStart(2, "0")
  const d = String(date.getDate()).padStart(2, "0")
  return `${y}-${m}-${d}`
}

export function fromISODate(iso) {
  const [y, m, d] = iso.split("-").map(Number)
  return new Date(y, m - 1, d)
}

export function minPickupISO() {
  return toISODate(addDays(new Date(), 2))
}

export function maxPickupISO() {
  return toISODate(addDays(new Date(), 14))
}

export function getMenuForISO(iso) {
  const dayIndex = fromISODate(iso).getDay()
  return MENUS[dayIndex]
}

export function formatDate(iso) {
  const date = fromISODate(iso)
  return date.toLocaleDateString(undefined, {
    weekday: "long",
    month: "long",
    day: "numeric",
    year: "numeric",
  })
}

export function formatCurrency(value) {
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
  }).format(value)
}

export function findItem(id) {
  for (const menu of MENUS) {
    for (const item of menu.items) {
      if (item.id === id) return item
    }
  }
  return null
}
