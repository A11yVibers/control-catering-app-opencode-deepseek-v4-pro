export const MENU = {
  monday,
  tuesday,
  wednesday,
  thursday,
  friday,
  saturday,
  sunday,
}

export function getDayMenu(dayKey) {
  return MENU[dayKey] || []
}

export function getMenuItem(dayKey, itemId) {
  return (MENU[dayKey] || []).find((item) => item.id === itemId) || null
}

export function resolveLine(line) {
  const item = getMenuItem(line.dayKey, line.itemId)
  if (!item) return null
  return { ...line, ...item }
}
